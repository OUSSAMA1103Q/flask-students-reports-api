def get_json_body():
    """Return the request body as a dict, or stop with 400 if it isn't valid JSON."""
    data = request.get_json(silent=True)  # silent=True: return None instead of raising
    if not isinstance(data, dict):
        abort(400, description="Request body must be a valid JSON object")
    return data


def require_fields(data, fields):
    missing = [field for field in fields if data.get(field) in (None, "")]
    if missing:
        abort(400, description=f"Missing required field(s): {', '.join(missing)}")


def validate_student(data):
    require_fields(data, STUDENT_FIELDS)
    if type(data["Diplome"]) is not int or data["Diplome"] not in (0, 1):
        abort(400, description="Diplome must be 0 or 1")
    if type(data["report_id"]) is not int:
        abort(400, description="report_id must be an integer")


def validate_report(data):
    require_fields(data, REPORT_FIELDS)
    date = data["Release_Date"]
    try:
        valid = datetime.strptime(date, "%Y-%m-%d").strftime("%Y-%m-%d") == date
    except (TypeError, ValueError):
        valid = False
    if not valid:
        abort(400, description="Release_Date must be a real date in the format YYYY-MM-DD")


# ---------------------------------------------------------------------------
# AUTH (JWT)
# ---------------------------------------------------------------------------
def create_token(username, token_type, lifetime):
    """Build a signed JWT. 'type' tells access and refresh tokens apart."""
    now = datetime.now(timezone.utc)
    payload = {
        "sub": username,
        "type": token_type,
        "iat": now,             # issued at
        "exp": now + lifetime,  # expiration: PyJWT rejects the token after this
    }
    return jwt.encode(payload, app.config["SECRET_KEY"], algorithm="HS256")


def decode_token(token, expected_type):
    """Check signature, expiration and type; stop with 401 if anything is wrong."""
    try:
        payload = jwt.decode(token, app.config["SECRET_KEY"], algorithms=["HS256"])
    except jwt.ExpiredSignatureError:
        abort(401, description="Token has expired")
    except jwt.InvalidTokenError:
        abort(401, description="Token is invalid")
    if payload.get("type") != expected_type:
        abort(401, description=f"Wrong token type: this endpoint needs the {expected_type} token")
    return payload


def token_required(view):
    """Decorator: only let the request through if it has a valid access token."""
    @wraps(view)
    def wrapper(*args, **kwargs):
        auth_header = request.headers.get("Authorization", "")
        parts = auth_header.split()
        if len(parts) != 2 or parts[0] != "Bearer":
            abort(401, description="Token is missing (expected 'Authorization: Bearer <token>')")
        decode_token(parts[1], "access")
        return view(*args, **kwargs)
    return wrapper


@app.route("/login", methods=["POST"])
def login():
    data = get_json_body()
    require_fields(data, ["username", "password"])
    if data["username"] != USER["username"] or data["password"] != USER["password"]:
        abort(401, description="Wrong username or password")
    return jsonify({
        "access_token": create_token(data["username"], "access", ACCESS_TOKEN_LIFETIME),
        "refresh_token": create_token(data["username"], "refresh", REFRESH_TOKEN_LIFETIME),
    })


@app.route("/refresh", methods=["POST"])
def refresh():
    data = get_json_body()
    require_fields(data, ["refresh_token"])
    payload = decode_token(data["refresh_token"], "refresh")
    return jsonify({
        "access_token": create_token(payload["sub"], "access", ACCESS_TOKEN_LIFETIME),
    })


