# ---------------------------------------------------------------------------
# HELPERS
# ---------------------------------------------------------------------------
def next_id(items, id_key):
    """New id = highest existing id + 1 (or 1 if the list is empty)."""
    highest = 0
    for item in items:
        if item[id_key] > highest:
            highest = item[id_key]
    return highest + 1


def find_or_404(items, id_key, item_id, label):
    """Loop through the list and return the item with that id, or stop with 404."""
    for item in items:
        if item[id_key] == item_id:
            return item
    abort(404, description=f"{label} with id {item_id} not found")


def count_students_for_report(report_id, ignore_student_id=None):
    """Count the students in the list that are linked to this report."""
    count = 0
    for student in students:
        if student["report_id"] == report_id and student["ID_S"] != ignore_student_id:
            count += 1
    return count


def check_report_link(report_id, ignore_student_id=None):
    """A student needs an existing report (404) that has fewer than 2 students (409)."""
    find_or_404(reports, "ID_R", report_id, "Report")
    if count_students_for_report(report_id, ignore_student_id) >= 2:
        abort(409, description=f"Report {report_id} already has 2 students")


