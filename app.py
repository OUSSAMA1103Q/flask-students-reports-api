@app.route("/students", methods=["POST"])
def create_student():
    data = get_json_body()
    validate_student(data)
    check_report_link(data["report_id"])
    student = {"ID_S": next_id(students, "ID_S")}
    for field in STUDENT_FIELDS:
        student[field] = data[field]
    students.append(student)
    return jsonify(student), 201


@app.route("/students/<int:student_id>", methods=["PUT"])
def update_student(student_id):
    student = find_or_404(students, "ID_S", student_id, "Student")
    data = get_json_body()
    validate_student(data)
    # ignore this student when counting, so keeping the same report is allowed
    check_report_link(data["report_id"], ignore_student_id=student_id)
    for field in STUDENT_FIELDS:
        student[field] = data[field]
    return jsonify(student)


@app.route("/students/<int:student_id>", methods=["DELETE"])
def delete_student(student_id):
    student = find_or_404(students, "ID_S", student_id, "Student")
    students.remove(student)
    return jsonify({"message": f"Student {student_id} deleted"})


